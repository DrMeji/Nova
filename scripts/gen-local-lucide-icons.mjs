/**
 * Regenerate src/lib/localLucideIcons.ts from the installed lucide-react package.
 * Offline icon source for create/edit Brand Assets (Iconify HTTP is fallback only).
 *
 *   node scripts/gen-local-lucide-icons.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = path.join(root, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const outFile = path.join(root, 'src', 'lib', 'localLucideIcons.ts');

/** Every lucide id referenced by brandAssets catalogs / plans / logo families. */
const NAMES = [
  'menu', 'search', 'user', 'settings', 'bell', 'heart', 'shopping-cart', 'shopping-bag', 'home',
  'mail', 'calendar', 'calendar-days', 'camera', 'mic', 'share-2', 'download', 'upload', 'trash-2',
  'pencil', 'lock', 'star', 'bookmark', 'circle-help', 'info', 'list-filter', 'layout-grid',
  'ellipsis', 'clock', 'map-pin', 'shield', 'utensils', 'library', 'book-marked', 'sparkles',
  'wind', 'leaf', 'wallet', 'music', 'dumbbell', 'message-circle', 'gamepad-2', 'cloud-sun',
  'plane', 'graduation-cap', 'coffee', 'wine', 'layout-dashboard', 'kanban', 'notebook-pen', 'package',
  'box', 'list-checks', 'calculator', 'timer', 'newspaper', 'video', 'shield-check', 'stethoscope',
  'car', 'palette', 'briefcase', 'sprout', 'chart-line', 'shirt', 'gem', 'building-2',
];

function readIcon(name, depth = 0) {
  const file = path.join(iconsDir, `${name}.js`);
  const src = fs.readFileSync(file, 'utf8');
  const alias = src.match(/export\s*\{\s*default\s*\}\s*from\s*'\.\/([\w-]+)\.js'/);
  if (alias && depth < 4) return readIcon(alias[1], depth + 1);
  const nodes = [...src.matchAll(/\[\s*"(\w+)"\s*,\s*\{([^}]*)\}\s*\]/g)];
  if (!nodes.length) throw new Error(`No icon nodes in ${name}`);
  return nodes.map(([, tag, attrs]) => {
    const pairs = [...attrs.matchAll(/(\w+)\s*:\s*"([^"]*)"/g)]
      .filter(([, k]) => k !== 'key')
      .map(([, k, v]) => `${k}="${v}"`);
    return `<${tag} ${pairs.join(' ')}/>`;
  }).join('');
}

const entries = NAMES.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(readIcon(n))},`);
const body = `/**
 * GENERATED by scripts/gen-local-lucide-icons.mjs from lucide-react (ISC).
 * Offline Lucide inner-SVG map — Brand Assets read this before any Iconify HTTP call.
 */

export const LOCAL_LUCIDE_ICONS: Record<string, string> = {
${entries.join('\n')}
};

export function hasLocalLucideIcon(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(LOCAL_LUCIDE_ICONS, String(name || '').toLowerCase());
}

/** Full standalone SVG for a Lucide icon id (e.g. "search"), or null when not bundled. */
export function localLucideSvg(name: string, ink = '#1a1a1a'): string | null {
  const key = String(name || '').toLowerCase();
  const inner = LOCAL_LUCIDE_ICONS[key];
  if (!inner) return null;
  return \`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="\${ink}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><title>\${key}</title>\${inner}</svg>\\n\`;
}

/** Same as localLucideSvg for an Iconify-style id ("lucide:search"); null for other collections. */
export function localIconifySvg(iconifyId: string, ink = '#1a1a1a'): string | null {
  const m = String(iconifyId || '').match(/^lucide:([a-z0-9-]+)$/i);
  return m ? localLucideSvg(m[1], ink) : null;
}
`;
fs.writeFileSync(outFile, body);
console.log(`wrote ${path.relative(root, outFile)} (${NAMES.length} icons)`);
