/**
 * Rebuild OPEN_ALL_CAPS from the FULL JSONL matrix (streaming — file can be >512MB).
 */
import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { fileURLToPath } from 'url';
import { spawnSync } from 'child_process';

const root = path.dirname(fileURLToPath(import.meta.url));
const dataPath = path.join(root, 'data', 'nova-deep-rescan.jsonl');
const capsOut = path.join(root, '../src/lib/inventOpenAllCaps.generated.ts');

function stem(cap) {
  let s = String(cap || '').trim();
  s = s.replace(/^C\d+\s+/i, '');
  s = s.replace(/^W\d+\s+/i, '');
  s = s.replace(/^Invent(?:80|100)?\s+/i, 'Invent ');
  s = s.replace(/^Seat(?:80|100)?\s+/i, 'Seat ');
  s = s.replace(/^Model(?:80|100)?\s+/i, 'Model ');
  s = s.replace(/^Kind(?:80|100)?\s+/i, 'Kind ');
  s = s.replace(/^Domain(?:80|100)?\s+/i, 'Domain ');
  s = s.replace(/^ImagePipe(?:80|100)?\s+/i, 'ImagePipe ');
  s = s.replace(/^Fidelity(?:80|100)?\s+/i, 'Fidelity ');
  s = s.replace(/^MaxModel(?:80|100)?\s+/i, 'MaxModel ');
  s = s.replace(/^Protocol(?:80|100)?\s+/i, 'Protocol ');
  s = s.replace(/^CoverageFid\s+W\d+\s+\d+\s+(\w+)\s+(\S+)\s+\S+/i, 'CoverageFid $1 $2');
  s = s.replace(/^CoveragePeer\s+W\d+\s+\d+\s+(\S+)\s+(.+?)\s+[a-f0-9]{6,}\s*$/i, 'CoveragePeer $1 $2');
  // Peer Cursor brief fidelity (Nova weaker) → Peer Cursor brief fidelity
  s = s.replace(
    /^Peer\s+(\S+)\s+(.+?)\s+\((?:Nova weaker|Nova missing|Nova partial|peer stronger UX|peer clearer plan)\)\s*$/i,
    'Peer $1 $2',
  );
  s = s.replace(/^Coverage\d+k\s+C\d+\s+\d+\s+(\w+)\s+(\S+)/i, 'Coverage $1 $2');
  s = s.replace(/^Coverage\d+k\s+\d+\s+(\w+)\s+(\S+)/i, 'Coverage $1 $2');
  return s.slice(0, 160);
}

const stems = new Set();
let rows = 0;
let strong = 0;

const rl = readline.createInterface({
  input: fs.createReadStream(dataPath, { encoding: 'utf8' }),
  crlfDelay: Infinity,
});
for await (const line of rl) {
  if (!line.trim()) continue;
  let r;
  try { r = JSON.parse(line); } catch { continue; }
  rows += 1;
  if (r.nova === 'strong') strong += 1;
  stems.add(stem(r.capability));
}

const caps = [...stems].sort((a, b) => a.localeCompare(b));
const gen = `/**
 * AUTO-GENERATED by scripts/_rebuild-open-all-from-matrix.mjs — do not edit.
 * Unique capability stems covering the full deep-rescan matrix (${rows} rows).
 * Full row list: scripts/data/nova-deep-rescan.jsonl
 */
export const OPEN_ALL_CAPS: string[] = ${JSON.stringify(caps)};
export const OPEN_ALL_MATRIX_ROWS = ${rows} as const;
`;
fs.writeFileSync(capsOut, gen);

console.log({
  matrixRows: rows,
  strong,
  uniqueStems: caps.length,
  capsBytes: Buffer.byteLength(gen),
  ratio: `${caps.length}/${rows}`,
});

const v = spawnSync(process.execPath, [path.join(root, '_verify-deep-rescan-wired.mjs')], {
  cwd: path.join(root, '..'),
  stdio: 'inherit',
});
if (v.status !== 0) process.exit(v.status || 1);
