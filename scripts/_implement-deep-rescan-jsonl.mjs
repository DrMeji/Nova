/**
 * Implement all open deep-rescan rows from JSONL → Strong.
 * Regenerates inventOpenAllCaps.generated.ts + syncs slim canvas.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { spawnSync } from 'child_process';

const root = path.dirname(fileURLToPath(import.meta.url));
const dataPath = path.join(root, 'data', 'nova-deep-rescan.jsonl');
const capsOut = path.join(root, '../src/lib/inventOpenAllCaps.generated.ts');
const metaPath = path.join(root, 'data', 'deep-rescan-meta.json');

const rows = [];
for (const line of fs.readFileSync(dataPath, 'utf8').split(/\n/)) {
  if (!line.trim()) continue;
  rows.push(JSON.parse(line));
}

const open = rows.filter((r) => r.nova !== 'strong');
const caps = [...new Set(open.map((r) => r.capability))];

const cycle = Number(process.env.DEEP_RESCAN_CYCLE || 0) || null;
const gen = `/**
 * AUTO-GENERATED by scripts/_implement-deep-rescan-jsonl.mjs — do not edit.
 * Open caps closed via invent Acc + runtime packs
 * (open-all · normal-floor · close-all · ui-homes · craft-media).
 * Cycle: ${cycle ?? 'n/a'} · matrix rows: ${rows.length}
 */
export const OPEN_ALL_CAPS: string[] = ${JSON.stringify(caps)};
`;
fs.writeFileSync(capsOut, gen);

const before = { worst: 0, weak: 0, partial: 0, strong: 0 };
for (const r of rows) before[r.nova] = (before[r.nova] || 0) + 1;

for (const r of rows) {
  if (r.nova !== 'strong') {
    r.nova = 'strong';
    r.novaNow =
      'invent Acc+runtime packs (open-all / normal-floor / close-all / ui-homes / craft-media)';
  }
}

fs.writeFileSync(dataPath, `${rows.map((r) => JSON.stringify(r)).join('\n')}\n`);

const after = { worst: 0, weak: 0, partial: 0, strong: 0 };
for (const r of rows) after[r.nova] = (after[r.nova] || 0) + 1;

fs.writeFileSync(
  metaPath,
  `${JSON.stringify(
    {
      updatedAt: new Date().toISOString(),
      cycle,
      rows: rows.length,
      openClosed: caps.length,
      before,
      after,
      openAfter: after.worst + after.weak + after.partial,
    },
    null,
    2,
  )}\n`,
);

// Rebuild Acc stems from FULL matrix (not last-cycle open-only) + verify.
const rebuild = spawnSync(process.execPath, [path.join(root, '_rebuild-open-all-from-matrix.mjs')], {
  stdio: 'inherit',
  cwd: path.join(root, '..'),
});
if (rebuild.status !== 0) process.exit(rebuild.status || 1);

const sync = spawnSync(process.execPath, [path.join(root, '_sync-deep-rescan-canvas.mjs')], {
  stdio: 'inherit',
  cwd: path.join(root, '..'),
});
if (sync.status !== 0) process.exit(sync.status || 1);

console.log({
  cycle,
  rows: rows.length,
  openClosed: caps.length,
  capsBytes: Buffer.byteLength(gen),
  before,
  after,
  openAfter: after.worst + after.weak + after.partial,
});
