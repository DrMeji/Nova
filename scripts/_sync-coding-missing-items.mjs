/**
 * Push coding-deep discoveries into Missing items tab
 * (src/lib/missingItemsDiscovered.generated.ts).
 * Cap UI list; full JSON stays in scripts/data/coding-missing-discovered.json.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { CODING_MISSING_PATH } from './lib/honestCatalog.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const outTs = path.join(root, '..', 'src', 'lib', 'missingItemsDiscovered.generated.ts');
const MAX_UI = Math.max(400, Number(process.env.MISSING_UI_CAP || 500));

let items = [];
if (fs.existsSync(CODING_MISSING_PATH)) {
  try {
    items = JSON.parse(fs.readFileSync(CODING_MISSING_PATH, 'utf8')).items || [];
  } catch {
    items = [];
  }
}

// Prefer critical + unique titles for the in-app Missing tab.
const seenTitle = new Set();
const ranked = [];
for (const i of items) {
  const t = String(i.title || '').toLowerCase();
  if (seenTitle.has(t)) continue;
  seenTitle.add(t);
  ranked.push(i);
}
ranked.sort((a, b) => Number(!!b.critical) - Number(!!a.critical));
const uiItems = ranked.slice(0, MAX_UI);

function esc(s) {
  return String(s ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r?\n/g, ' ');
}

const lit = uiItems
  .map(
    (i) => `  {
    id: '${esc(i.id)}',
    title: '${esc(i.title)}',
    why: '${esc(i.why)}',
    eventualHome: '${esc(i.eventualHome || 'code-header')}',
    homeLabel: '${esc(i.homeLabel || 'Coding-deep discovery')}',
    critical: ${i.critical ? 'true' : 'false'},
  }`,
  )
  .join(',\n');

// No import from missingItemsCatalog — avoids Vite circular export failure.
const src = `/**
 * AUTO-GENERATED by scripts/_sync-coding-missing-items.mjs — do not edit.
 * UI cap ${MAX_UI} (full archive: scripts/data/coding-missing-discovered.json).
 */
export type DiscoveredMissingItem = {
  id: string;
  title: string;
  why: string;
  eventualHome:
    | 'settings-ai'
    | 'settings-privacy'
    | 'settings-projects'
    | 'settings-providers'
    | 'settings-advanced'
    | 'chat-composer'
    | 'chat-side'
    | 'code-header'
    | 'live-chrome'
    | 'workspace'
    | 'nav-tools'
    | 'agents-window'
    | 'new-surface';
  homeLabel: string;
  critical: boolean;
  diskFilesOnly?: boolean;
};

export const DISCOVERED_MISSING_TOTAL = ${items.length};
export const DISCOVERED_MISSING_ITEMS: DiscoveredMissingItem[] = [
${lit}
];
`;

fs.writeFileSync(outTs, src);
console.log(JSON.stringify({
  archive: items.length,
  uiWrote: uiItems.length,
  path: outTs,
}, null, 2));
