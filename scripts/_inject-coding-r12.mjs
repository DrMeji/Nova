function mapGap(g) {
  const x = String(g || '').toLowerCase();
  if (x === 'have') return 'Have';
  if (x === 'partial' || x === 'weak') return 'Partial';
  if (x === 'missing') return 'Missing';
  if (x === 'conflict') return 'Conflict';
  return 'Partial';
}

function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

