/**
 * Milestone implement (runs at 500k / 1M / … before research continues):
 *  1) Sync full Missing archive → in-app Missing tab (higher UI cap)
 *  2) Group every item by eventualHome (Settings / Agents / Live / …)
 *  3) Write by-home placement manifest + generated TS for the app
 *  4) Mark placement complete in checkpoint sidecar
 *
 * Does NOT reset the coding catalog. Safe to re-run.
 */
import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';
import { fileURLToPath } from 'url';
import { CODING_MISSING_PATH } from './lib/honestCatalog.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const project = path.join(root, '..');
const milestone = Number(process.env.MILESTONE || 0) || null;
const byHomePath = path.join(root, 'data', 'coding-missing-by-home.json');
const placeTs = path.join(project, 'src', 'lib', 'missingItemsByHome.generated.ts');
const donePath = path.join(root, 'data', 'coding-milestone-implement.json');

const HOME_LABEL = {
  'settings-ai': 'Settings → AI',
  'settings-privacy': 'Settings → Privacy',
  'settings-projects': 'Settings → Projects',
  'settings-providers': 'Settings → Providers',
  'settings-advanced': 'Settings → Advanced / Storage',
  'chat-composer': 'Chat composer chrome',
  'chat-side': 'Chat side panel',
  'code-header': 'Code / project header',
  'live-chrome': 'Live preview chrome',
  workspace: 'Project workspace',
  'nav-tools': 'Sidebar Tools',
  'agents-window': 'Agents Window',
  'new-surface': 'New dedicated surface',
};

// Push a large slice into the Missing tab UI for this milestone.
const uiCap = String(process.env.MISSING_UI_CAP || 2000);
const sync = spawnSync(
  process.execPath,
  [path.join(root, '_sync-coding-missing-items.mjs')],
  {
    cwd: project,
    stdio: 'inherit',
    env: { ...process.env, MISSING_UI_CAP: uiCap },
  },
);
if (sync.status !== 0) {
  console.error('missing sync failed', sync.status);
  process.exit(sync.status || 1);
}

let items = [];
if (fs.existsSync(CODING_MISSING_PATH)) {
  try {
    items = JSON.parse(fs.readFileSync(CODING_MISSING_PATH, 'utf8')).items || [];
  } catch {
    items = [];
  }
}

/** @type {Record<string, object[]>} */
const byHome = {};
for (const item of items) {
  const home = String(item.eventualHome || 'new-surface');
  (byHome[home] ||= []).push({
    id: item.id,
    title: item.title,
    why: item.why,
    critical: Boolean(item.critical),
    homeLabel: HOME_LABEL[home] || item.homeLabel || home,
  });
}

const summary = Object.fromEntries(
  Object.entries(byHome).map(([home, list]) => [
    home,
    {
      homeLabel: HOME_LABEL[home] || home,
      count: list.length,
      critical: list.filter((x) => x.critical).length,
    },
  ]),
);

const doc = {
  updatedAt: new Date().toISOString(),
  milestone,
  archiveTotal: items.length,
  homes: summary,
  byHome,
};
fs.writeFileSync(byHomePath, `${JSON.stringify(doc, null, 2)}\n`);

function esc(s) {
  return String(s ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r?\n/g, ' ');
}

const homeKeys = Object.keys(HOME_LABEL);
const lit = homeKeys
  .map((home) => {
    const list = byHome[home] || [];
    const rows = list
      .slice(0, 400)
      .map(
        (i) => `    { id: '${esc(i.id)}', title: '${esc(i.title)}', critical: ${i.critical ? 'true' : 'false'} }`,
      )
      .join(',\n');
    return `  '${home}': {\n    homeLabel: '${esc(HOME_LABEL[home])}',\n    total: ${list.length},\n    items: [\n${rows}\n    ],\n  }`;
  })
  .join(',\n');

const ts = `/**
 * AUTO-GENERATED by scripts/_implement-coding-milestone.mjs — do not edit.
 * Missing discoveries routed to their eventual homes for Settings / Agents / Live / …
 */
export type MissingHomeId =
  | 'settings-ai'
  | 'settings-privacy'
  | 'settings-projects'
  | 'settings-providers'
  | 'settings-advanced'
  | 'chat-composer'
  | 'chat-side'
  | 'code-header'
  | 'live-chrome'
  | 'workspace'
  | 'nav-tools'
  | 'agents-window'
  | 'new-surface';

export const MISSING_BY_HOME_TOTAL = ${items.length};
export const MISSING_BY_HOME_MILESTONE = ${milestone == null ? 'null' : String(milestone)};
export const MISSING_BY_HOME: Record<
  MissingHomeId,
  { homeLabel: string; total: number; items: Array<{ id: string; title: string; critical: boolean }> }
> = {
${lit}
};
`;

fs.writeFileSync(placeTs, ts);

const done = {
  at: new Date().toISOString(),
  milestone,
  archiveTotal: items.length,
  homes: summary,
  byHomePath,
  placeTs,
  note:
    'Items are routed by eventualHome into HomeControlsPanel on each Settings/Agents/Live home. Open those surfaces to see switches; Missing tab keeps the full staging list.',
};
fs.writeFileSync(donePath, `${JSON.stringify(done, null, 2)}\n`);

console.log(JSON.stringify({
  ok: true,
  milestone,
  archiveTotal: items.length,
  homes: summary,
  byHomePath,
  placeTs,
}, null, 2));
